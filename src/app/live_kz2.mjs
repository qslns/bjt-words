import { chromium } from 'playwright';
const browser = await chromium.launch({ ...(process.env.PW_CHROME ? { executablePath: process.env.PW_CHROME } : {}) });
const ctx = await browser.newContext({ viewport: { width: 1180, height: 820 }, serviceWorkers: 'block' });
const page = await ctx.newPage(); const errs = [];
page.on('pageerror', e => errs.push(String(e)));
page.on('console', m => { if (m.type() === 'error' && !/Failed to load resource|fonts\.g/.test(m.text())) errs.push(m.text()); });
await page.goto('https://qslns.github.io/bjt-words/?t=' + Date.now());
await page.waitForSelector('#v-home details.gf', { state: 'attached', timeout: 60000 });
const r = { ver: await page.textContent('#v-home .ver') };
r.groups = await page.locator('#v-home details.gf').count();
r.kzGroup = await page.locator('#v-home details[data-g="kz"]').count();
await page.locator('#v-home details[data-g="kz"] > summary').click(); await page.waitForTimeout(200);
await page.locator('#v-home details[data-g="kz"] .book').first().click();
await page.waitForTimeout(800);
r.view = await page.evaluate(() => [...document.querySelectorAll('section.view')].filter(s => !s.hidden).map(s => s.id).join(','));
r.front = (await page.locator('#v-kz').innerText()).slice(0, 60).replace(/\n/g, ' ');
await page.locator('#v-kz [data-act="kzExplain"], #v-kz button:has-text("해설")').first().click(); await page.waitForTimeout(500);
r.card = await page.locator('#v-kz .kz-card').count();
r.errs = errs; console.log(JSON.stringify(r)); await browser.close();
