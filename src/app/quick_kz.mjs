import { chromium } from 'playwright';
const browser = await chromium.launch({ ...(process.env.PW_CHROME ? { executablePath: process.env.PW_CHROME } : {}) });
const ctx = await browser.newContext({ viewport: { width: 1180, height: 820 }, serviceWorkers: 'block' });
const page = await ctx.newPage(); const errs = [];
page.on('pageerror', e => errs.push(String(e)));
page.on('console', m => { if (m.type() === 'error' && !/Failed to load resource|fonts\.g/.test(m.text())) errs.push(m.text()); });
await page.goto('https://qslns.github.io/bjt-words/?t=' + Date.now());
await page.waitForSelector('#v-home details.gf', { state: 'attached' });
const r = {};
r.groups = await page.locator('#v-home details.gf').count();
r.kzGroup = await page.locator('#v-home [data-g="kz"]').count();
const wid = await page.evaluate(() => JSON.parse(document.getElementById('bjt-data').textContent).words.find(w => w.w === '確認').id);
await page.evaluate(id => { document.body.insertAdjacentHTML('beforeend', '<button id="tmp-open" data-act="open" data-id="' + id + '">x</button>'); document.getElementById('tmp-open').click(); document.getElementById('tmp-open').remove(); }, wid);
await page.waitForSelector('#sheet:not([hidden]) .s-story', { timeout: 8000 });
r.storyLabel = await page.evaluate(() => (document.querySelector('#sheet-body .s-story .sl') || {}).textContent);
r.kp = await page.locator('#sheet-body .s-kp').count();
await page.screenshot({ path: '/home/claude/work/app/qk_word.png' });
await page.locator('#sheet-body .s-story [data-act="kz"]').first().click();
await page.waitForTimeout(400);
r.title1 = await page.textContent('#sheet-title');
r.card = await page.locator('#sheet-body .kz-card').count();
r.back = await page.locator('#sheet-back:not([hidden])').count();
await page.screenshot({ path: '/home/claude/work/app/qk_kanji.png' });
await page.locator('#sheet-body .kz-card [data-act="open"]').nth(1).click();
await page.waitForTimeout(400);
r.title2 = await page.textContent('#sheet-title');
await page.locator('#sheet-back').click(); await page.waitForTimeout(300);
r.title3 = await page.textContent('#sheet-title');
await page.locator('#sheet-back').click(); await page.waitForTimeout(300);
r.title4 = await page.textContent('#sheet-title');
r.errs = errs;
console.log(JSON.stringify(r));
await browser.close();
